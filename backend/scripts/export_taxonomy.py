"""Generate the Flutter copy of the qualification taxonomy.

    cd backend && python scripts/export_taxonomy.py

Writes mobile/lib/domain/qualification_taxonomy.g.dart. tests/test_taxonomy.py
fails when the committed file is out of date, so run this after editing
app/domain/qualifications.py.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))

from app.domain.qualifications import DEGREES, LEVEL_LABELS, OTHERS, QualificationLevel  # noqa: E402

DART_FILE = BACKEND.parent / "mobile" / "lib" / "domain" / "qualification_taxonomy.g.dart"


def _s(value: str | None) -> str:
    return "null" if value is None else json.dumps(value, ensure_ascii=False).replace("$", r"\$")


def render() -> str:
    lines = [
        "// GENERATED by backend/scripts/export_taxonomy.py from",
        "// backend/app/domain/qualifications.py. Do not edit by hand.",
        "",
        "import 'qualification_taxonomy.dart';",
        "",
        f"const kOthersDegreeCode = {_s(OTHERS)};",
        "",
        "const kQualificationLevels = <QualificationLevel>[",
    ]
    for lv in QualificationLevel:
        lines.append(f"  QualificationLevel({_s(lv.value)}, {_s(LEVEL_LABELS[lv])}, {lv.rank}),")
    lines += ["];", "", "const kDegrees = <DegreeOption>["]
    for d in DEGREES:
        lines.append(f"  DegreeOption({_s(d.code)}, {_s(d.label)}, {_s(d.level.value)}, {_s(d.group)}),")
    lines += ["];", ""]
    return "\n".join(lines)


def main() -> None:
    DART_FILE.write_text(render(), encoding="utf-8", newline="\n")
    print(f"Wrote {DART_FILE}")


if __name__ == "__main__":
    main()
